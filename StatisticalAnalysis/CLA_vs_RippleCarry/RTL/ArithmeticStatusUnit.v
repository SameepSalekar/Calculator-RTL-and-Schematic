module ArithmeticStatusUnit
#(
    parameter WIDTH = 4
)
(
    input wire [WIDTH - 1:0] Result,
    input wire CarryOut,
    input wire CarryIntoMSB,

    output wire Zero,
    output wire Negative,
    output wire Carry,
    output wire Overflow
);

    // Zero flag:
    // Asserted when every bit of the result is zero.
    assign Zero = (Result == {WIDTH{1'b0}});

    // Negative flag:
    // The most significant bit represents the sign bit.
    assign Negative = Result[WIDTH - 1];

    // Carry flag:
    // Final carry generated by the adder/subtractor.
    assign Carry = CarryOut;

    // Overflow flag:
    // Signed overflow occurs when the carry into the
    // most significant bit differs from the carry out.
    assign Overflow = CarryIntoMSB ^ CarryOut;

endmodule
